_EVENT_PREFIX: Dict[str, str] = {
    "injury": "受了点伤：",
    "onset": "病了：",
    "resolve": "好些了：",
    "onset_risk": "身体有点不对：",
}


def event_text(ev: str) -> str:
    """把事件代号转成可读中文。带冒号的形如 onset:流感。"""
    ev = (ev or "").strip()
    if not ev:
        return ""
    if ":" in ev:
        head, tail = ev.split(":", 1)
        return _EVENT_PREFIX.get(head, head + "：") + tail
    return EVENT_ZH.get(ev, ev)


def events_text(events, limit: int = 6, sep: str = "；") -> str:
    out: List[str] = []
    for ev in list(events or [])[-limit:]:
        t = event_text(ev)
        if t and t not in out:
            out.append(t)
    return sep.join(out)



